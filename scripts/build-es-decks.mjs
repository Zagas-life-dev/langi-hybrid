function parseCard(line, defTag) {
  const [term, translation, posRaw = '', genderRaw = '', tagsRaw = ''] = line.split('|').map((s) => s.trim())
  const extraTags = []
  // The pos/gender fields may tack on extra tags after a comma
  // ("phrase, informal" / "f, drink"); keep the first token, tag the rest.
  let partOfSpeech = ''
  if (posRaw) { const [p, ...rest] = posRaw.split(',').map((s) => s.trim()); partOfSpeech = p; extraTags.push(...rest) }
  let gender = ''
  if (genderRaw) { const [g, ...rest] = genderRaw.split(',').map((s) => s.trim()); gender = g; extraTags.push(...rest) }

  const art = term.match(/^(el|la|los|las)\s+/i)
  if (!partOfSpeech) {
    if (art) { partOfSpeech = 'noun'; if (!gender) gender = /^(el|los)$/i.test(art[1]) ? 'm' : 'f' }
    else partOfSpeech = 'phrase'
  } else if (partOfSpeech === 'noun' && !gender && art) {
    gender = /^(el|los)$/i.test(art[1]) ? 'm' : 'f'
  }

  const explicitTags = tagsRaw ? tagsRaw.split(',').map((t) => t.trim()) : []
  const tags = [...explicitTags, ...extraTags].filter(Boolean)
  const card = { term, translation, partOfSpeech, tags: tags.length ? tags : [defTag] }
  if (gender === 'm' || gender === 'f') card.gender = gender // ignore stray non-gender tokens
  return card
}

